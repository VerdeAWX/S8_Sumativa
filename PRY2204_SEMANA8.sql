/* ============================================================
   1. PAIS
   IDENTITY:
   inicia en 9
   incrementa en 3
   ============================================================ */

CREATE TABLE PAIS (
    id_pais NUMBER(3)
        GENERATED BY DEFAULT AS IDENTITY
        (START WITH 9 INCREMENT BY 3),

    nom_pais VARCHAR2(30) NOT NULL,

    CONSTRAINT PAIS_PK
        PRIMARY KEY (id_pais),

    CONSTRAINT PAIS_UN_NOM
        UNIQUE (nom_pais)
);


/* ============================================================
   2. CIUDAD
   ============================================================ */

CREATE TABLE CIUDAD (
    id_ciudad NUMBER(3) NOT NULL,
    nom_ciudad VARCHAR2(30) NOT NULL,
    cod_pais NUMBER(3) NOT NULL,

    CONSTRAINT CIUDAD_PK
        PRIMARY KEY (id_ciudad),

    CONSTRAINT CIUDAD_FK_PAIS
        FOREIGN KEY (cod_pais)
        REFERENCES PAIS(id_pais),

    CONSTRAINT CIUDAD_UN_NOM
        UNIQUE (nom_ciudad, cod_pais)
);


/* ============================================================
   3. CLIENTE
   ============================================================ */

CREATE TABLE CLIENTE (
    rut NUMBER(8) NOT NULL,
    dv CHAR(1) NOT NULL,
    pnombre VARCHAR2(20) NOT NULL,
    snombre VARCHAR2(20),
    apaterno VARCHAR2(20) NOT NULL,
    amaterno VARCHAR2(20) NOT NULL,
    telefono VARCHAR2(12),
    email VARCHAR2(40),
    tipo_cli CHAR(1) NOT NULL,

    CONSTRAINT CLIENTE_PK
        PRIMARY KEY (rut),

    CONSTRAINT CLIENTE_UN_EMAIL
        UNIQUE (email),

    CONSTRAINT CLIENTE_CK_DV
        CHECK (REGEXP_LIKE(dv, '^[0-9Kk]$')),

    CONSTRAINT CLIENTE_CK_TIPO
        CHECK (tipo_cli IN ('P', 'E'))
);


/* ============================================================
   4. PREMIUM
   ============================================================ */

CREATE TABLE PREMIUM (
    cl_rut NUMBER(8) NOT NULL,
    pesos_clientes NUMBER(10) NOT NULL,
    monto_credito NUMBER(10),

    CONSTRAINT PREMIUM_PK
        PRIMARY KEY (cl_rut),

    CONSTRAINT PREMIUM_FK_CLIENTE
        FOREIGN KEY (cl_rut)
        REFERENCES CLIENTE(rut),

    CONSTRAINT PREMIUM_CK_PESOS
        CHECK (pesos_clientes >= 0),

    CONSTRAINT PREMIUM_CK_CREDITO
        CHECK (monto_credito IS NULL OR monto_credito >= 0)
);


